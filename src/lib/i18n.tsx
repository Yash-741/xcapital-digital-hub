type Ctx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string) => string;
  tEn: (englishSource: string) => string;
};
const I18nContext = createContext<Ctx | null>(null);

function applyGoogleTranslate(lang: Lang) {
  if (typeof document === "undefined") return;
  const cookieVal = lang === "en" ? "" : `/en/${lang}`;
  const host = typeof location !== "undefined" ? location.hostname : "";
  const expires = lang === "en" ? "Thu, 01 Jan 1970 00:00:00 GMT" : "";
  const attr = expires ? `; expires=${expires}` : "";
  document.cookie = `googtrans=${cookieVal}; path=/${attr}`;
  if (host) {
    document.cookie = `googtrans=${cookieVal}; path=/; domain=${host}${attr}`;
    document.cookie = `googtrans=${cookieVal}; path=/; domain=.${host}${attr}`;
  }
  const combo = document.querySelector<HTMLSelectElement>(".goog-te-combo");
  if (combo) {
    combo.value = lang === "en" ? "" : lang;
    combo.dispatchEvent(new Event("change"));
    if (lang === "en") {
      // Combo back-to-original sometimes leaves stale text; force restore.
      window.setTimeout(() => location.reload(), 50);
    }
  } else {
    // Widget not ready yet — reload so cookie kicks in on next load.
    if (lang !== "en") window.setTimeout(() => location.reload(), 50);
  }
}

const _missingWarned = new Set<string>();
function reportMissing(lang: Lang, key: string) {
  if (lang === "en") return;
  const tag = `${lang}::${key}`;
  if (_missingWarned.has(tag)) return;
  _missingWarned.add(tag);
  if (typeof console !== "undefined") {
    console.warn(`[i18n] Missing ${lang} translation for: ${key}`);
  }
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    const saved = (typeof window !== "undefined" && (localStorage.getItem(STORAGE_KEY) as Lang)) || "en";
    setLangState(saved);
    if (typeof document !== "undefined") document.documentElement.lang = saved;
  }, []);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    if (typeof window !== "undefined") {
      localStorage.setItem(STORAGE_KEY, l);
      document.documentElement.lang = l;
      applyGoogleTranslate(l);
    }
  }, []);

  useEffect(() => {
    if (typeof window === "undefined") return;
    const saved = (localStorage.getItem(STORAGE_KEY) as Lang) || "en";
    if (saved !== "en") {
      // Wait until the Google widget injects .goog-te-combo, then apply.
      let tries = 0;
      const id = window.setInterval(() => {
        tries += 1;
        if (document.querySelector(".goog-te-combo") || tries > 40) {
          window.clearInterval(id);
          applyGoogleTranslate(saved);
        }
      }, 250);
      return () => window.clearInterval(id);
    }
  }, []);

  const t = useCallback(
    (key: string) => {
      const hit = DICTS[lang][key];
      if (hit !== undefined) return hit;
      reportMissing(lang, key);
      const fallback = DICTS.en[key] ?? key;
      return lang === "en" ? fallback : `${fallback} ⚠`;
    },
    [lang],
  );
  const tEn = useCallback(
    (s: string) => {
      if (lang === "en") return s;
      const hit = EN_DICTS[lang][s];
      if (hit !== undefined) return hit;
      reportMissing(lang, s);
      return `${s} ⚠`;
    },
    [lang],
  );

  const value = useMemo(() => ({ lang, setLang, t, tEn }), [lang, setLang, t, tEn]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) return {
    lang: "en" as Lang,
    setLang: () => {},
    t: (k: string) => DICTS.en[k] ?? k,
    tEn: (s: string) => s,
  };
  return ctx;
}